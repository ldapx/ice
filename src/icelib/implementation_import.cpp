std::string nowUtc() {
    const auto now = std::chrono::system_clock::now();
    const auto time = std::chrono::system_clock::to_time_t(now);
    std::tm calendar{};
#ifdef _WIN32
    gmtime_s(&calendar, &time);
#else
    gmtime_r(&time, &calendar);
#endif
    std::ostringstream output;
    output << std::put_time(&calendar, "%Y-%m-%dT%H:%M:%SZ");
    return output.str();
}

std::string lowercase(std::string value) {
    std::transform(value.begin(), value.end(), value.begin(),
                   [](unsigned char character) { return static_cast<char>(std::tolower(character)); });
    return value;
}

std::string referenceFormatForPath(const std::filesystem::path &path) {
    const auto extension = lowercase(path.extension().string());
    if (extension == ".oas" || extension == ".oasis")
        return "oasis";
    if (extension == ".gds" || extension == ".gdsii")
        return "gds";
    return {};
}

std::filesystem::path findImplementationStream(const std::filesystem::path &runDirectory) {
    for (const auto *candidate :
         {"final/6_final.gds", "final/6_final.gdsii", "final/6_final.oas", "final/6_final.oasis"}) {
        const auto path = runDirectory / candidate;
        std::error_code status;
        if (std::filesystem::is_regular_file(path, status) && !status)
            return path;
    }
    std::error_code status;
    const auto directory = runDirectory / "final";
    if (!std::filesystem::is_directory(directory, status) || status)
        return {};
    std::filesystem::path newest;
    std::filesystem::file_time_type newestTime{};
    for (std::filesystem::directory_iterator iterator(directory, status), end; !status && iterator != end;
         iterator.increment(status)) {
        if (!iterator->is_regular_file())
            continue;
        if (referenceFormatForPath(iterator->path()).empty())
            continue;
        const auto time = iterator->last_write_time(status);
        if (status)
            continue;
        if (newest.empty() || time > newestTime) {
            newest = iterator->path();
            newestTime = time;
        }
    }
    return newest;
}

constexpr const char *kFlattenDeviceScript = R"(# Generated by ICE. Do not edit by hand.
import json
import pya

config = globals().get("config", "")
if not config:
    raise SystemExit("missing flatten config")
with open(config, "r", encoding="utf-8") as handle:
    cfg = json.load(handle)

layout = pya.Layout()
layout.read(cfg["input"])
design = cfg.get("top", "")
cell = layout.cell(design) if design else None
if cell is None:
    tops = layout.top_cells()
    if len(tops) != 1:
        raise SystemExit("final stream needs an explicit top cell")
    cell = tops[0]
cell.flatten(-1)

for layer_index in list(layout.layer_indices()):
    shapes = cell.shapes(layer_index)
    for shape in list(shapes.each()):
        if shape.is_path():
            shapes.replace(shape, shape.path.polygon())
        elif shape.is_box():
            box = shape.box
            shapes.replace(shape, pya.Polygon([
                pya.Point(box.left, box.bottom),
                pya.Point(box.right, box.bottom),
                pya.Point(box.right, box.top),
                pya.Point(box.left, box.top),
            ]))

output = pya.Layout()
output.dbu = layout.dbu
top = output.create_cell(cell.name)
top.copy_tree(cell)
output.write(cfg["out"])
)";

void writeTextFile(const std::filesystem::path &path, const std::string &text) {
    std::filesystem::create_directories(path.parent_path());
    std::ofstream output(path, std::ios::binary | std::ios::trunc);
    if (!output)
        throw ProjectError("implementation.device", "Unable to write " + path.string());
    output << text;
}

std::filesystem::path flattenImplementationStream(const std::filesystem::path &stream, const std::string &top,
                                                  const std::filesystem::path &projectRoot, const std::string &runStem,
                                                  int timeoutSeconds) {
    const auto referenceRoot = projectRoot / "build" / "layout-references";
    std::filesystem::create_directories(referenceRoot);
    const auto output = referenceRoot / (runStem + "-device.gds");
    std::error_code status;
    if (std::filesystem::is_regular_file(output, status) && !status) {
        const auto outputTime = std::filesystem::last_write_time(output, status);
        if (!status) {
            const auto inputTime = std::filesystem::last_write_time(stream, status);
            if (!status && outputTime >= inputTime)
                return output;
        }
    }
    const auto toolchain = discoverImplementationToolchain();
    if (toolchain.klayout.path.empty())
        throw ProjectError("implementation.device",
                           "KLayout is required to flatten the final stream into a device cell");
    const auto scriptPath = referenceRoot / ("flatten-" + runStem + ".py");
    const auto configPath = referenceRoot / ("flatten-" + runStem + ".json");
    const auto logPath = referenceRoot / ("flatten-" + runStem + ".log");
    writeTextFile(scriptPath, kFlattenDeviceScript);
    nlohmann::json config = {{"input", stream.generic_string()}, {"top", top}, {"out", output.generic_string()}};
    writeTextFile(configPath, config.dump(2) + "\n");
    ProcessOptions process;
    process.arguments = {toolchain.klayout.path.generic_string(), "-b", "-z", "-r", scriptPath.generic_string(), "-rd",
                         "config=" + configPath.generic_string()};
    process.workingDirectory = referenceRoot;
    process.logPath = logPath;
    process.timeoutSeconds = timeoutSeconds > 0 ? timeoutSeconds : 300;
    const auto processResult = runProcess(process);
    if (!processResult.succeeded()) {
        std::ifstream log(logPath, std::ios::binary);
        std::ostringstream text;
        text << log.rdbuf();
        auto details = text.str();
        if (details.size() > 4000)
            details = details.substr(0, 4000);
        throw ProjectError("implementation.device",
                           "Unable to flatten the final stream: " + (details.empty() ? "KLayout failed" : details));
    }
    if (!std::filesystem::is_regular_file(output, status) || status)
        throw ProjectError("implementation.device", "KLayout did not write the flattened device stream");
    return output;
}

void copyFlattenedStream(Project &project, LayoutCell &cell, const std::filesystem::path &flattened,
                         const PackageSpec &package, const std::string &pdk, const std::string &stack) {
    auto imported = LayoutInterchange::importGds(flattened);
    if (imported.layoutCells.empty())
        throw ProjectError("implementation.device", "The flattened device stream contains no layout cell");
    const auto &source = imported.layoutCells.begin()->second;
    std::map<ObjectId, ObjectId> layers;
    for (const auto &[id, layer] : imported.layers) {
        ObjectId target = 0;
        for (const auto &[candidateId, candidate] : project.layers) {
            if (candidate.layout != 0 || candidate.number != layer.number || candidate.datatype != layer.datatype)
                continue;
            if (!candidate.pdk.empty() && candidate.pdk != pdk)
                continue;
            if (!candidate.stack.empty() && candidate.stack != stack)
                continue;
            target = candidateId;
            break;
        }
        if (target == 0) {
            std::string name = layer.name;
            if (package.pdk) {
                for (const auto &packageLayer : package.pdk->layers) {
                    if (packageLayer.number == layer.number && packageLayer.datatype == layer.datatype) {
                        name = packageLayer.name;
                        break;
                    }
                }
            }
            target = addLayer(project, name, layer.number, 0, pdk, layer.datatype, stack);
        }
        layers[id] = target;
    }
    for (const auto &[_, shape] : source.shapes) {
        const auto layer = layers.find(shape.layer);
        if (layer == layers.end())
            continue;
        auto copy = shape;
        copy.id = project.nextId();
        copy.layer = layer->second;
        copy.net.reset();
        copy.routedConnection = 0;
        cell.shapes.emplace(copy.id, std::move(copy));
    }
    for (const auto &[_, port] : source.ports) {
        const auto layer = layers.find(port.layer);
        if (layer == layers.end())
            continue;
        auto copy = port;
        copy.id = project.nextId();
        copy.layer = layer->second;
        copy.net = 0;
        copy.sourceInstance = 0;
        copy.sourcePort = 0;
        cell.ports.emplace(copy.id, std::move(copy));
    }
}

std::string uniqueLayoutName(const Project &project, const std::string &name) {
    const auto taken = [&](const std::string &candidate) {
        for (const auto &[_, cell] : project.layoutCells)
            if (cell.name == candidate)
                return true;
        for (const auto &[_, procedural] : project.proceduralLayouts)
            if (procedural.name == candidate)
                return true;
        return false;
    };
    if (!taken(name))
        return name;
    for (int suffix = 2;; ++suffix) {
        const auto candidate = name + " " + std::to_string(suffix);
        if (!taken(candidate))
            return candidate;
    }
}


constexpr const char *kFlattenScript = R"(# Generated by ICE. Do not edit by hand.
import json
import os
import pya

config = globals().get("config", "")
if not config:
    raise SystemExit("missing reference preview config")
with open(config, "r", encoding="utf-8") as handle:
    cfg = json.load(handle)

layout = pya.Layout()
layout.read(cfg["input"])
design = cfg.get("top", "")
cell = layout.cell(design) if design else None
if cell is None:
    tops = layout.top_cells()
    if len(tops) != 1:
        raise SystemExit("GDS/OASIS reference needs an explicit top cell")
    cell = tops[0]
cell.flatten(-1)

for layer_index in list(layout.layer_indices()):
    shapes = cell.shapes(layer_index)
    for shape in list(shapes.each()):
        if shape.is_path():
            shapes.replace(shape, shape.path.polygon())
        elif shape.is_box():
            box = shape.box
            shapes.replace(shape, pya.Polygon([
                pya.Point(box.left, box.bottom),
                pya.Point(box.right, box.bottom),
                pya.Point(box.right, box.top),
                pya.Point(box.left, box.top),
            ]))

output = pya.Layout()
output.dbu = layout.dbu
top = output.create_cell(cell.name)
top.copy_tree(cell)
output_path = cfg["out"]
parent = os.path.dirname(output_path)
if parent:
    os.makedirs(parent, exist_ok=True)
output.write(output_path)
)";

std::string lowerCopy(std::string text) {
    for (auto &character : text)
        character = static_cast<char>(std::tolower(static_cast<unsigned char>(character)));
    return text;
}

void writeText(const std::filesystem::path &path, const std::string &text) {
    std::filesystem::create_directories(path.parent_path());
    std::ofstream output(path, std::ios::binary | std::ios::trunc);
    if (!output)
        throw ProjectError("layout.reference", "Unable to write " + path.string());
    output << text;
}

std::string readText(const std::filesystem::path &path) {
    std::ifstream input(path, std::ios::binary);
    if (!input)
        return {};
    std::ostringstream text;
    text << input.rdbuf();
    return text.str();
}

std::string findKlayout() {
    if (const auto *configured = std::getenv("ICE_KLAYOUT"); configured && *configured)
        return configured;
    const auto found = QStandardPaths::findExecutable(QStringLiteral("klayout"));
    return found.toStdString();
}


LayoutReferencePreview loadLayoutReferencePreview(const LayoutReference &reference, const Project &styleProject,
                                                  const std::string &pdk, const std::string &stack,
                                                  const std::filesystem::path &projectRoot,
                                                  const std::filesystem::path &cacheRoot) {
    LayoutReferencePreview result;
    const auto source = std::filesystem::path(reference.path).is_absolute() ? std::filesystem::path(reference.path)
                                                                            : projectRoot / reference.path;
    std::error_code status;
    if (!std::filesystem::is_regular_file(source, status) || status) {
        result.error =
            QStringLiteral("Reference stream does not exist: %1").arg(QString::fromStdString(source.string()));
        return result;
    }

    const auto klayout = findKlayout();
    if (klayout.empty()) {
        result.error = QStringLiteral("KLayout is required to render GDS/OASIS references. Set ICE_KLAYOUT.");
        return result;
    }

    const auto modified = std::filesystem::last_write_time(source, status);
    const auto size = std::filesystem::file_size(source, status);
    std::ostringstream keyBuilder;
    keyBuilder << lowerCopy(reference.format) << "|" << source.generic_string() << "|" << reference.topCell << "|"
               << size << "|" << modified.time_since_epoch().count();
    const auto key = std::to_string(std::hash<std::string>{}(keyBuilder.str()));

    std::filesystem::create_directories(cacheRoot);
    const auto scriptPath = cacheRoot / "flatten_reference.py";
    const auto configPath = cacheRoot / ("reference-" + key + ".json");
    const auto logPath = cacheRoot / ("reference-" + key + ".log");
    const auto gdsPath = cacheRoot / ("reference-" + key + ".gds");
    writeText(scriptPath, kFlattenScript);

    if (!std::filesystem::is_regular_file(gdsPath, status) || status) {
        nlohmann::json config = {
            {"input", source.generic_string()}, {"top", reference.topCell}, {"out", gdsPath.generic_string()}};
        writeText(configPath, config.dump(2) + "\n");

        ProcessOptions process;
        process.arguments = {
            klayout, "-b", "-z", "-r", scriptPath.generic_string(), "-rd", "config=" + configPath.generic_string()};
        process.logPath = logPath;
        process.timeoutSeconds = 300;
        const auto processResult = runProcess(process);
        if (!processResult.succeeded() || !std::filesystem::is_regular_file(gdsPath, status) || status) {
            std::string details = readText(logPath);
            if (details.size() > 4000)
                details = details.substr(0, 4000);
            result.error = QStringLiteral("Unable to read the GDS/OASIS reference: %1")
                               .arg(QString::fromStdString(details.empty() ? "KLayout failed" : details));
            return result;
        }
    }

    try {
        auto project = std::make_shared<Project>(LayoutInterchange::importGds(gdsPath));
        if (project->layoutCells.empty()) {
            result.error = QStringLiteral("Reference preview contains no layout cells.");
            return result;
        }
        const auto cellId = project->layoutCells.begin()->first;
        const auto &cell = project->layoutCells.at(cellId);
        result.model = buildLayoutCellPreviewModel(*project, cell, true, true, false);
        if (result.model.empty()) {
            result.error = QStringLiteral("Reference preview contains no geometry.");
            return result;
        }

        const auto remapLayer = [&](LayoutPreviewLayer &layer) {
            ObjectId matched = 0;
            for (const auto &[id, candidate] : styleProject.layers) {
                if (candidate.number != layer.number || candidate.datatype != layer.datatype)
                    continue;
                if (!pdk.empty() && !candidate.pdk.empty() && candidate.pdk != pdk)
                    continue;
                if (!stack.empty() && !candidate.stack.empty() && candidate.stack != stack)
                    continue;
                matched = id;
                if (lowerCopy(candidate.name) == lowerCopy(layer.name.toStdString()))
                    break;
            }
            if (matched != 0) {
                const auto &candidate = styleProject.layers.at(matched);
                layer.id = matched;
                layer.name = QString::fromStdString(candidate.name);
            }
        };
        for (auto &shape : result.model.shapes)
            remapLayer(shape.layer);
        for (auto &port : result.model.ports)
            remapLayer(port.layer);
        return result;
    } catch (const std::exception &error) {
        result.error = QString::fromUtf8(error.what());
        return result;
    }
}

